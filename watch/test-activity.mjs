import assert from 'node:assert/strict'
import {MotionWindow, StepSession, snapshot} from './page/activity.js'

const motion = new MotionWindow()
for (let i=0;i<20;i++) motion.add({x:0,y:0,z:981},100+i/10)
let value=motion.take()
assert.equal(value.rms_variation_cm_s2,0, 'Constant gravity must not count as movement')
assert.equal(value.peak_change_cm_s2,0)
assert.equal(value.samples,20)
assert.equal(motion.take(),null)
motion.add({x:0,y:0,z:981},200)
motion.add({x:100,y:0,z:981},201)
value=motion.take()
assert.equal(value.rms_variation_cm_s2,50)
assert.equal(value.peak_change_cm_s2,100)
assert.equal(value.window_start,200)
assert.equal(value.ts,201)
motion.add({x:NaN,y:0,z:981},300)
motion.add({x:0,y:0,z:981},300)
assert.equal(motion.take(),null,'One sample cannot establish motion variation')
motion.add({x:0,y:0,z:981},300)
motion.add({x:100,y:0,z:981},301)
motion.add({x:200,y:0,z:981},330)
assert.equal(motion.take(),null,'A suspension starts a new observation window')

const steps = new StepSession(100)
assert.equal(steps.observe(1234,100).since_start,0)
assert.equal(steps.observe(1244,102).since_start,10)
assert.equal(steps.observe(1244,104).since_start,10)
assert.equal(steps.observe(-1,105),null)
assert.equal(steps.observe(1244,NaN),null)
assert.equal(steps.observe(0,106).since_start,10,'Midnight resets the baseline')
assert.equal(steps.observe(3,108).since_start,13)
assert.equal(new StepSession(110).observe(3,110).since_start,0)
const packet=snapshot(200,{ts:180,bpm:72},{ts:200,count:10},null)
assert.equal(packet.heart_rate,undefined,'Fresh steps cannot refresh an old pulse')
assert.equal(packet.steps.ts,200)
assert.equal(snapshot(200,null,null,null),null)
assert.equal(snapshot(200,{ts:201,bpm:72},null,null),null)
console.log('Activity tests passed: gravity baseline, known motion, missing samples, suspension, counter reset, fresh timestamps.')
